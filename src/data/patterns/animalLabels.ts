function pickUnique(pool: readonly string[], count: number, seed: number): string[] {
  const rng = mulberry32(seed)
  const bag = [...pool]
  const out: string[] = []
  for (let i = 0; i < count; i++) {
    if (bag.length === 0) bag.push(...pool.map((n) => `${n} (${i + 1})`))
    const idx = Math.floor(rng() * bag.length)
    out.push(bag.splice(idx, 1)[0]!)
  }
  return out
}

export function generateSpeciesNames(count: number, seed: number): string[] {
  return pickUnique(SPECIES_NAMES, count, seed)
}

export function generateSubspeciesNames(count: number, seed: number): string[] {
  return pickUnique(SUBSPECIES_NAMES, count, seed + 17)
}

export function animalNameForTreeDepth(depth: number, index: number): string {
  if (depth === 0) return SPECIES_NAMES[index % SPECIES_NAMES.length]!
  if (depth === 1) return SUBSPECIES_NAMES[index % SUBSPECIES_NAMES.length]!
  return LOCAL_POPULATION_NAMES[index % LOCAL_POPULATION_NAMES.length]!
}
